// Node's type-stripping loader requires source extensions at runtime.
// @ts-expect-error TS5097: this module is also executed with --experimental-strip-types.
import { createFontAssay } from "./font-assay.ts";
// @ts-expect-error TS5097: this module is also executed with --experimental-strip-types.
import { tokenManifest } from "./manifest.ts";
// @ts-expect-error TS5097: this module is also executed with --experimental-strip-types.
import { TOKEN_SECTION_ORDER } from "./schema.ts";
import type { TokenDefinition, TokenSectionName, TokenTheme } from "./schema";
// @ts-expect-error TS5097: this module is also executed with --experimental-strip-types.
import { assertValidTokenManifest, tokenValueToCss } from "./validation.ts";

export const GENERATED_ARTIFACT_PATHS = Object.freeze([
  "frontend/src/design-system/generated/tokens.css",
  "frontend/src/design-system/generated/tokens.ts",
  "docs/assets/design-tokens.json",
] as const);

export type GeneratedArtifactPath = (typeof GENERATED_ARTIFACT_PATHS)[number];
export type GeneratedArtifacts = Readonly<
  Record<GeneratedArtifactPath, string>
>;

type V2SectionName = Exclude<TokenSectionName, "compatV1">;

const V2_SECTION_ORDER = TOKEN_SECTION_ORDER.slice(
  0,
  -1,
) as readonly V2SectionName[];

function compareOrdinal(left: string, right: string): number {
  return left === right ? 0 : left < right ? -1 : 1;
}

function sortedEntries<T>(record: Readonly<Record<string, T>>): [string, T][] {
  return Object.entries(record).sort(([left], [right]) =>
    compareOrdinal(left, right),
  );
}

function fontAssayContract() {
  return createFontAssay(
    tokenManifest.primitive["type.family.sans"].values.light,
  );
}

function renderDefinitionDeclarations(
  definitions: readonly [string, TokenDefinition][],
  theme: TokenTheme,
  indent: string,
): string[] {
  return definitions.map(
    ([, definition]) =>
      `${indent}${definition.cssVariable}: ${tokenValueToCss(
        tokenManifest,
        definition.values[theme],
      )};`,
  );
}

function renderV2Theme(theme: TokenTheme, indent: string): string[] {
  const lines: string[] = [];
  for (const section of V2_SECTION_ORDER) {
    lines.push(`${indent}/* ${section} */`);
    lines.push(
      ...renderDefinitionDeclarations(
        sortedEntries(tokenManifest[section]),
        theme,
        indent,
      ),
    );
  }
  return lines;
}

function renderCompatTheme(theme: "light" | "dark", indent: string): string[] {
  return sortedEntries(tokenManifest.compatV1).map(
    ([cssVariable, values]) => `${indent}${cssVariable}: ${values[theme]};`,
  );
}

function semanticColorEntries(): [string, TokenDefinition][] {
  return sortedEntries(tokenManifest.semanticV2).filter(
    ([, definition]) => definition.kind === "color",
  );
}

function utilityBridgeVariable(definition: TokenDefinition): string {
  return `--ds-utility-${definition.cssVariable.slice(2)}`;
}

function renderTailwindThemeMappings(): string[] {
  return semanticColorEntries().map(
    ([, definition]) =>
      `  ${definition.cssVariable}: var(${utilityBridgeVariable(definition)});`,
  );
}

function renderUtilityBridges(indent: string): string[] {
  return semanticColorEntries().map(
    ([, definition]) =>
      `${indent}${utilityBridgeVariable(definition)}: var(${definition.cssVariable});`,
  );
}

function renderTokensCss(): string {
  const light = renderV2Theme("light", "    ");
  const dark = renderV2Theme("dark", "    ");
  const highContrast = renderV2Theme("highContrast", "      ");
  const compatLight = renderCompatTheme("light", "    ");
  const compatDark = renderCompatTheme("dark", "    ");
  const systemDark = renderV2Theme("dark", "      ");
  const compatSystemDark = renderCompatTheme("dark", "      ");

  return [
    "/* Generated by tooling/design-system/tokens/generate.mts. DO NOT EDIT. */",
    "/* Opt-in scopes keep Design System V2 inert until a route explicitly adopts it. */",
    "@theme inline {",
    ...renderTailwindThemeMappings(),
    "}",
    "",
    "@layer design-system-tokens {",
    '  :where([data-design-system="v2"]) {',
    "    color-scheme: light;",
    ...light,
    "    /* Tailwind mappings resolve only inside an adopted V2 scope. */",
    ...renderUtilityBridges("    "),
    "  }",
    "",
    '  :where([data-design-system="v2"][data-theme="dark"], [data-theme="dark"] [data-design-system="v2"]:not([data-theme="light"], [data-theme="light"] *)) {',
    "    color-scheme: dark;",
    ...dark,
    "  }",
    "",
    "  /* Exact V1 snapshot, also opt-in; no :root declaration is emitted. */",
    '  :where([data-design-system="v1"]) {',
    "    color-scheme: light;",
    ...compatLight,
    "  }",
    "",
    '  :where([data-design-system="v1"][data-theme="dark"], [data-theme="dark"] [data-design-system="v1"]:not([data-theme="light"], [data-theme="light"] *)) {',
    "    color-scheme: dark;",
    ...compatDark,
    "  }",
    "",
    "  @media (prefers-color-scheme: dark) {",
    '    :where([data-design-system="v2"]:not([data-theme="light"], [data-theme="light"] *)) {',
    "      color-scheme: dark;",
    ...systemDark,
    "    }",
    "",
    '    :where([data-design-system="v1"]:not([data-theme="light"], [data-theme="light"] *)) {',
    "      color-scheme: dark;",
    ...compatSystemDark,
    "    }",
    "  }",
    "",
    "  @media (forced-colors: active) {",
    '    :where([data-design-system="v2"]) {',
    ...highContrast,
    "      forced-color-adjust: auto;",
    "    }",
    "  }",
    "",
    "  @media (prefers-reduced-motion: reduce) {",
    '    :where([data-design-system="v2"]) {',
    "      --ds-motion-duration-instant: 0ms;",
    "      --ds-motion-duration-feedback: 0ms;",
    "      --ds-motion-duration-fast: 0ms;",
    "      --ds-motion-duration-standard: 0ms;",
    "      --ds-motion-duration-deliberate: 0ms;",
    "      --ds-motion-duration-narrative-max: 0ms;",
    "      --ds-motion-displacement-xs: 0px;",
    "      --ds-motion-displacement-sm: 0px;",
    "      --ds-motion-displacement-md: 0px;",
    "      --ds-motion-displacement-lg: 0px;",
    "    }",
    "",
    '    :where([data-design-system="v1"]) {',
    "      --duration-instant: 0ms;",
    "      --duration-fast: 0ms;",
    "      --duration-normal: 0ms;",
    "      --duration-slow: 0ms;",
    "    }",
    "  }",
    "}",
    "",
  ].join("\n");
}

function orderedV2Section(section: V2SectionName) {
  return Object.fromEntries(sortedEntries(tokenManifest[section]));
}

function orderedCompatSection() {
  return Object.fromEntries(sortedEntries(tokenManifest.compatV1));
}

function generatedContract() {
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $version: "2.0.0",
    $description:
      "Generated TryVit Living Label token contract. Source: frontend/src/design-system/tokens/manifest.ts. Generated files must not be hand-edited.",
    fontAssay: fontAssayContract(),
    primitive: orderedV2Section("primitive"),
    semanticV2: orderedV2Section("semanticV2"),
    componentV2: orderedV2Section("componentV2"),
    domain: orderedV2Section("domain"),
    compatV1: orderedCompatSection(),
  } as const;
}

function renderTokensTs(): string {
  const contract = generatedContract();
  const serialized = JSON.stringify(contract, null, 2);
  return [
    "/* Generated by tooling/design-system/tokens/generate.mts. DO NOT EDIT. */",
    `export const generatedTokenContract = ${serialized} as const;`,
    "",
    "export const tokenNames = {",
    ...V2_SECTION_ORDER.map((section) => {
      const names = Object.fromEntries(
        sortedEntries(tokenManifest[section]).map(([tokenId, definition]) => [
          tokenId,
          definition.cssVariable,
        ]),
      );
      return `  ${section}: ${JSON.stringify(names, null, 2).replace(/\n/g, "\n  ")},`;
    }),
    `  compatV1: ${JSON.stringify(
      Object.fromEntries(
        sortedEntries(tokenManifest.compatV1).map(([cssVariable]) => [
          cssVariable,
          cssVariable,
        ]),
      ),
      null,
      2,
    ).replace(/\n/g, "\n  ")},`,
    "} as const;",
    "",
    "export type PrimitiveTokenName = keyof typeof tokenNames.primitive;",
    "export type SemanticV2TokenName = keyof typeof tokenNames.semanticV2;",
    "export type ComponentV2TokenName = keyof typeof tokenNames.componentV2;",
    "export type DomainTokenName = keyof typeof tokenNames.domain;",
    "export type CompatV1TokenName = keyof typeof tokenNames.compatV1;",
    "export type DesignSystemTheme = \"light\" | \"dark\" | \"highContrast\";",
    "",
  ].join("\n");
}

function renderDocsJson(): string {
  return `${JSON.stringify(generatedContract(), null, 2)}\n`;
}

export function buildGeneratedArtifacts(): GeneratedArtifacts {
  assertValidTokenManifest(tokenManifest);
  return Object.freeze({
    "frontend/src/design-system/generated/tokens.css": renderTokensCss(),
    "frontend/src/design-system/generated/tokens.ts": renderTokensTs(),
    "docs/assets/design-tokens.json": renderDocsJson(),
  });
}
